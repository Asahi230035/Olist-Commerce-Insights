-- =========================================
-- Olist 数据库视图查询汇总
-- 数据库：olist_analysis
-- 视图数量：10
-- =========================================

USE olist_analysis;


-- =========================================
-- 一、数据清洗与标准化视图
-- =========================================

-- 1. 查看订单清洗结果
-- 包含订单时间质量、配送时长及延迟判定等信息
SELECT *
FROM v_orders_clean
LIMIT 20;


-- 2. 查看商品标准化结果
-- 包含商品类别翻译、缺失类别处理及尺寸有效性
SELECT *
FROM v_products_clean
LIMIT 20;


-- 3. 查看评价清洗结果
-- 包含评价评分、文本完整性及重复关系
SELECT *
FROM v_reviews_clean
LIMIT 20;


-- 4. 查看地理位置标准化结果
-- 按邮编前缀聚合，保留代表地区及冲突标记
SELECT *
FROM v_geolocation_clean
LIMIT 20;



-- =========================================
-- 二、订单粒度聚合视图
-- =========================================

-- 5. 查看订单商品金额聚合结果
-- 将同一订单的多条商品明细聚合到订单粒度
SELECT *
FROM v_order_items_agg
LIMIT 20;


-- 6. 查看订单支付金额聚合结果
-- 避免多次支付记录在关联时重复计算
SELECT *
FROM v_payments_agg
LIMIT 20;


-- 7. 查看订单评价聚合结果
-- 将同一订单的多条评价汇总到订单粒度
SELECT *
FROM v_reviews_agg
LIMIT 20;



-- =========================================
-- 三、核心业务分析视图
-- =========================================

-- 8. 查看订单级综合分析数据
-- 一笔订单对应一行
-- 用于经营规模、GMV、AOV、配送等分析
SELECT *
FROM v_order_analysis
LIMIT 20;


-- 9. 查看商品明细级综合分析数据
-- 每条订单商品明细对应一行
-- 用于商品品类、商家及地区分析
SELECT *
FROM v_order_item_analysis
LIMIT 20;


-- 10. 查看真实客户级综合分析数据
-- 一个 customer_unique_id 对应一行
-- 用于购买频次、客户价值及 RFM 分析
SELECT *
FROM v_customer_analysis
LIMIT 20;